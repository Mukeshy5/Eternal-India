// Money is calculated in integer paise on both sides of the API.
export function calculateInvoice(totalPerson, perPersonAmount) {
  if (!["string", "number"].includes(typeof totalPerson) || !["string", "number"].includes(typeof perPersonAmount)) return null;
  const quantity = String(totalPerson), rate = String(perPersonAmount);
  if (!/^[1-9]\d{0,5}$/.test(quantity) || !/^\d{1,8}(?:\.\d{1,2})?$/.test(rate)) return null;
  const [whole, fraction = ""] = rate.split("."), ratePaise = Number(whole) * 100 + Number(fraction.padEnd(2, "0"));
  const totalPaise = Number(quantity) * ratePaise;
  if (!ratePaise || !Number.isSafeInteger(totalPaise) || totalPaise > 999999999999) return null;
  return { totalPerson: Number(quantity), perPersonAmount: ratePaise / 100, totalAmount: totalPaise / 100, totalPaise };
}
